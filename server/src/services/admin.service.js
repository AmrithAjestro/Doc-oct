const path = require('path');
const { Op } = require('sequelize');
const config = require('../config/config');
const { ROLES, DOCTOR_STATUS } = require('../config/constants');
const { DoctorProfile, User, Appointment } = require('../models');
const AppError = require('../utils/AppError');
const { parsePagination, pageMeta } = require('../utils/helpers');
const { notify } = require('./notification.service');
const { getSettings } = require('./settings.service');
const { cancelFutureFor } = require('./appointment.service');
const { removeFile } = require('../middlewares/upload.middleware');

// doctors

async function listDoctors(query) {
  const paging = parsePagination(query);
  const where = {};
  if (query.status) where.status = query.status;
  if (query.search) {
    const term = `%${query.search}%`;
    where[Op.or] = [{ '$user.name$': { [Op.iLike]: term } }, { '$user.email$': { [Op.iLike]: term } }, { specialization: { [Op.iLike]: term } }];
  }
  const { rows, count } = await DoctorProfile.findAndCountAll({
    where,
    include: [{ model: User, as: 'user' }],
    order: [
      // Pending reviews first, oldest first within them.
      [require('sequelize').literal(`CASE "DoctorProfile"."status" WHEN 'pending' THEN 0 ELSE 1 END`), 'ASC'],
      ['createdAt', 'ASC']
    ],
    limit: paging.limit,
    offset: paging.offset,
    distinct: true
  });
  return { rows, meta: pageMeta(paging, count) };
}

async function getDoctor(id) {
  const doctor = await DoctorProfile.findByPk(id, {
    include: [{ model: User, as: 'user' }, { model: User, as: 'reviewer', attributes: ['id', 'name'] }]
  });
  if (!doctor) throw AppError.notFound('Doctor not found');
  const stats = await Appointment.count({ where: { doctorId: id }, group: ['status'] });
  return { ...doctor.toJSON(), appointmentStats: Object.fromEntries(stats.map((s) => [s.status, Number(s.count)])) };
}

async function reviewDoctor(admin, id, { status, reason }) {
  const doctor = await DoctorProfile.findByPk(id, { include: [{ model: User, as: 'user' }] });
  if (!doctor) throw AppError.notFound('Doctor not found');
  if (status === DOCTOR_STATUS.REJECTED && !reason) throw AppError.badRequest('Please give the doctor a reason for the rejection', 'REASON_REQUIRED');
  if (status === DOCTOR_STATUS.APPROVED && !doctor.certificatePath) throw AppError.rule('This doctor has not uploaded a certificate', 'NO_CERTIFICATE');
  if (doctor.status === status) throw AppError.conflict(`Doctor is already ${status}`);

  const wasApproved = doctor.status === DOCTOR_STATUS.APPROVED;
  await doctor.update({
    status,
    rejectionReason: status === DOCTOR_STATUS.REJECTED ? reason : null,
    reviewedAt: new Date(),
    reviewedBy: admin.id
  });

  let cancelled = 0;
  if (wasApproved && status !== DOCTOR_STATUS.APPROVED) {
    cancelled = await cancelFutureFor({ doctorId: doctor.id }, { by: ROLES.ADMIN, reason: 'The doctor is no longer available on the platform' });
  }

  await notify(doctor.userId, {
    type: `doctor_${status}`,
    title: status === DOCTOR_STATUS.APPROVED ? 'Profile approved' : 'Profile not approved',
    message:
      status === DOCTOR_STATUS.APPROVED
        ? 'Your profile has been approved. You can now add availability slots and receive bookings.'
        : `Your profile was not approved. Reason: ${reason}. You can upload a new certificate from your profile.`
  });
  return { doctor, cancelledAppointments: cancelled };
}

function certificateFile(doctor) {
  if (!doctor?.certificatePath) throw AppError.notFound('No certificate uploaded');
  // Stored names are generated by us, but never trust a path component.
  return {
    path: path.join(config.UPLOAD_DIR, 'certificates', path.basename(doctor.certificatePath)),
    name: doctor.certificateName || 'certificate',
    mimeType: doctor.certificateMimeType
  };
}

// users

async function listUsers(query) {
  const paging = parsePagination(query);
  const where = {};
  if (query.role) where.role = query.role;
  if (query.status) where.isActive = query.status === 'active';
  if (query.search) {
    const term = `%${query.search}%`;
    where[Op.or] = [{ name: { [Op.iLike]: term } }, { email: { [Op.iLike]: term } }, { phone: { [Op.iLike]: term } }];
  }
  const { rows, count } = await User.findAndCountAll({
    where,
    include: [{ model: DoctorProfile, as: 'doctorProfile', attributes: ['id', 'status', 'specialization'] }],
    order: [['createdAt', 'DESC']],
    limit: paging.limit,
    offset: paging.offset
  });
  return { rows, meta: pageMeta(paging, count) };
}

async function setUserActive(admin, id, isActive) {
  const user = await User.findByPk(id, { include: [{ model: DoctorProfile, as: 'doctorProfile' }] });
  if (!user) throw AppError.notFound('User not found');
  if (user.id === admin.id) throw AppError.rule('You cannot deactivate your own account');
  if (user.isActive === isActive) return { user, cancelledAppointments: 0 };

  await user.update({ isActive });
  let cancelled = 0;
  if (!isActive) {
    const reason = 'The account was deactivated by the administrator';
    if (user.role === ROLES.USER) cancelled = await cancelFutureFor({ userId: user.id }, { by: ROLES.ADMIN, reason });
    if (user.role === ROLES.DOCTOR && user.doctorProfile) {
      cancelled = await cancelFutureFor({ doctorId: user.doctorProfile.id }, { by: ROLES.ADMIN, reason: 'The doctor is no longer available on the platform' });
    }
  }
  return { user, cancelledAppointments: cancelled };
}

// settings

async function updateSettings(data) {
  const settings = await getSettings();
  const type = data.commissionType ?? settings.commissionType;
  const value = data.commissionValue ?? settings.commissionValue;
  if (type === 'percentage' && value > 100) throw AppError.badRequest('A percentage commission cannot exceed 100', 'INVALID_COMMISSION');
  // Existing appointments keep the price they were booked at; only new bookings use the new commission.
  return settings.update(data);
}

async function updateLogo(file) {
  if (!file) throw AppError.badRequest('Please attach a logo image', 'FILE_REQUIRED');
  const settings = await getSettings();
  const old = settings.logoPath;
  await settings.update({ logoPath: file.filename });
  if (old) removeFile(path.join(config.UPLOAD_DIR, 'branding', path.basename(old)));
  return settings;
}

async function removeLogo() {
  const settings = await getSettings();
  if (settings.logoPath) removeFile(path.join(config.UPLOAD_DIR, 'branding', path.basename(settings.logoPath)));
  return settings.update({ logoPath: null });
}

module.exports = { listDoctors, getDoctor, reviewDoctor, certificateFile, listUsers, setUserActive, updateSettings, updateLogo, removeLogo };
